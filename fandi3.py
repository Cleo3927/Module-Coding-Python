"""**Tokenization**"""

import tiktoken

enc = tiktoken.get_encoding("cl100k_base")

def tokenize_text(text):
    tokens = enc.encode(text)
    token_strs = [enc.decode([t]) for t in tokens]
    return tokens, token_strs

eng_tokens, eng_strs = tokenize_text(english_text)
chi_tokens, chi_strs = tokenize_text(chinese_text)
pol_tokens, pol_strs = tokenize_text(polish_text)

