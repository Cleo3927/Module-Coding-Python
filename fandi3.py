"""**Word-level statistics**"""

import re
import pandas as pd

def word_token_stats(text, token_strs, lang="English"):
    if lang == "Chinese":
        words = list(text.replace(" ", "").replace("\n", ""))
    else:
        words = re.findall(r'\S+', text)
    token_counts = [len(enc.encode(w)) for w in words]
    total_words = len(words)
    total_tokens = len(token_strs)
    one = sum(1 for c in token_counts if c == 1) / total_words
    two = sum(1 for c in token_counts if c == 2) / total_words
    three_plus = sum(1 for c in token_counts if c >= 3) / total_words
    avg = total_tokens / total_words
    return {
        "total_words": total_words,
        "total_tokens": total_tokens,
        "%1_token": round(one * 100, 2),
        "%2_tokens": round(two * 100, 2),
        "%3+_tokens": round(three_plus * 100, 2),
        "avg_tokens_per_word": round(avg, 2)
    }

stats = pd.DataFrame([
    word_token_stats(english_text, eng_strs, "English"),
    word_token_stats(chinese_text, chi_strs, "Chinese"),
    word_token_stats(polish_text, pol_strs, "Polish")
], index=["English", "Chinese", "Polish"])

stats

